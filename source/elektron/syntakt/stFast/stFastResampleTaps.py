#!/usr/bin/env python3
"""Writes stFastResampleTaps.inc, the taps of Resample48To44, from a formula alone: python stFastResampleTaps.py

The prototype: 20 kHz, -6 dB there, Kaiser beta 7, 7681 taps at 147 x 48 kHz. Its minimum-phase twin: the same magnitude
by the real cepstrum, folded on a 2^23 FFT, the magnitude floored 240 dB below its peak where the stopband's zeros would
take the log to -inf. Its first 48 x 147 taps are the table, phase by phase, each phase's oldest input's tap first: phase
p's tap k weighs the input k samples before, at [p][47 - k].

A table and not code run at start: 2^15 points would take 5 ms in C++ and land 34 dB from these taps, 2^18 takes 54 ms and
lands 62 dB from them, and a filter of these points is what was listened to."""
import pathlib

import numpy as np

UP, RATE = 147, 48000.0
LENGTH = 7681
CUTOFF, BETA = 20000.0, 7.0
TAPS = 48                   # per phase
NFFT, FLOOR_DB = 1 << 23, -240.0
PER_LINE = 7


def prototype():
    fc = CUTOFF / (UP * RATE)
    t = np.arange(LENGTH) - (LENGTH - 1) / 2
    return UP * (2 * fc * np.sinc(2 * fc * t)) * np.kaiser(LENGTH, BETA)


def minimum_phase(h):
    magnitude = np.abs(np.fft.rfft(h, NFFT))
    magnitude = np.maximum(magnitude, magnitude.max() * 10 ** (FLOOR_DB / 20))
    cepstrum = np.fft.irfft(np.log(magnitude), NFFT)
    cepstrum[1:NFFT // 2] *= 2
    cepstrum[NFFT // 2 + 1:] = 0
    return np.fft.irfft(np.exp(np.fft.rfft(cepstrum)), NFFT)


def main():
    taps = minimum_phase(prototype())[:TAPS * UP].astype(np.float32)
    rows = taps.reshape(TAPS, UP).T[:, ::-1].ravel()
    lines = [",".join("%.9ef" % v for v in rows[i:i + PER_LINE]) + ",\n" for i in range(0, len(rows), PER_LINE)]
    path = pathlib.Path(__file__).with_suffix(".inc")
    path.write_text("// Generated by stFastResampleTaps.py\n" + "".join(lines), newline="\n")
    print(len(taps), "taps, gain at 0 Hz", taps.sum(dtype=np.float64) / UP)


if __name__ == "__main__":
    main()
